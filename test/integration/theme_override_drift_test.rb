# frozen_string_literal: true

require "test_helper"

# The Civora public theme (docs/appearance.md) overrides two Decidim files by
# copy: the footer's mini partial (one marked block) and the Tailwind config
# template. A Decidim bump that changes either would otherwise keep serving the
# stale copy silently; these fail until the copy is re-based.
class ThemeOverrideDriftTest < ActiveSupport::TestCase
  test "the footer mini override is the gem partial plus the marked Civora block" do
    path = "app/views/layouts/decidim/footer/_mini.html.erb"
    spec = Gem::Specification.find_by_name("decidim-core")
    gem_lines = File.read(File.join(spec.full_gem_path, path)).lines
    host_lines = Rails.root.join(path).read.lines
    host_lines.shift(host_lines.index { |line| line.include?("%>") } + 1) # the header comment

    start = host_lines.index { |line| line.include?("<%# Civora: start %>") }
    finish = host_lines.index { |line| line.include?("<%# Civora: end %>") }
    assert start && finish && start < finish, "the Civora block markers are missing"

    body = host_lines[0...start] + host_lines[(finish + 1)..]
    assert_equal gem_lines, body, "#{path} drifted from decidim-core #{spec.version}: re-copy it and re-insert the Civora block"
  end

  # Lines the host template changes on purpose, exactly as the gem writes them.
  # Every other line of the gem template must still be in the host copy.
  REPLACED_TEMPLATE_LINES = [
    "// This file is automatically generated.",
    "// Do not edit this file, it will be overwritten",
    "// If you want to modify it, follow instructions from",
    "// https://docs.decidim.org/en/develop/customize/styles",
    'black: "#020203",',
    'DEFAULT: "#6B7280CC", // 80% opacity',
    '2: "#3E4C5C",',
    '3: "#E1E5EF",',
    '4: "#242424",',
    '5: "#F6F8FA",',
    '6: "#D3D5D9"',
    'DEFAULT: "#F3F4F7",',
    '2: "#FAFBFC",',
    '3: "#EFEFEF",',
    '4: "#E4EEFF99", // 60% opacity',
    '5: "#E9E9E9"',
    'sans: ["Source Sans Pro", "ui-sans-serif", "system-ui", "sans-serif"]'
  ].freeze

  test "the tailwind template override still carries every untouched line of the decidim-core template" do
    path = "lib/decidim/assets/tailwind/tailwind.config.js.erb"
    spec = Gem::Specification.find_by_name("decidim-core")
    gem_lines = File.read(File.join(spec.full_gem_path, path)).lines.map(&:strip).reject(&:empty?)
    host_lines = Rails.root.join("config/tailwind.config.js.erb").read.lines.map(&:strip)

    gem_lines.each do |line|
      next if REPLACED_TEMPLATE_LINES.include?(line)

      assert_includes host_lines, line, "config/tailwind.config.js.erb drifted from decidim-core #{spec.version}: missing #{line.inspect}"
    end
    REPLACED_TEMPLATE_LINES.each do |line|
      assert_includes gem_lines, line, "decidim-core #{spec.version} no longer has #{line.inspect}: re-base config/tailwind.config.js.erb"
    end
  end

  test "the host template leaves the organization colours to Decidim" do
    template = Rails.root.join("config/tailwind.config.js.erb").read

    %w(primary secondary tertiary).each do |name|
      assert_includes template, %(#{name}: withOpacity("--#{name}-rgb"))
    end
  end
end
